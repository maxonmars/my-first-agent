import { z } from "zod";

function jsonType(value: unknown): string {
  return value === null ? "null" : Array.isArray(value) ? "array" : typeof value;
}

export const factsSchema = z.record(
  z.string().refine((value) => value.trim().length > 0),
  z
    .string({ error: (issue) => `значение факта должно быть строкой, получено ${jsonType(issue.input)}` })
    .refine((value) => value.trim().length > 0, { error: "значение факта — пустая строка" }),
  {
    error: (issue) =>
      issue.code === "invalid_key"
        ? "ключ факта должен быть непустой строкой"
        : `ожидается JSON-объект со строковыми значениями, получено ${jsonType(issue.input)}`,
  },
);
